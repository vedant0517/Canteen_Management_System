package com.canteen;

import java.math.BigDecimal;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.util.ArrayList;
import java.util.List;
import java.util.Set;

/**
 * OrderDAO.java - Data Access Object for orders table.
 *
 * This class handles all database operations related to orders:
 * - Placing a new order (INSERT)
 * - Retrieving all orders with food item names (SELECT with JOIN)
 * - Updating order status (UPDATE)
 *
 * All SQL is obtained from QueryGenerator.
 * User-supplied values are set via PreparedStatement placeholders.
 * The total amount is calculated in Java using BigDecimal for accuracy.
 */
public class OrderDAO {

    // Valid order statuses
    private static final Set<String> VALID_STATUSES = Set.of(
            "Pending", "Preparing", "Completed"
    );

    /**
     * Places a new order.
     *
     * Steps:
     * 1. Verify the food item exists and is available.
     * 2. Fetch the current price from the database (not from the UI).
     * 3. Calculate total_amount = price × quantity using BigDecimal.
     * 4. Insert the order into the database.
     *
     * @param itemId   the food item ID to order
     * @param quantity the number of units to order (must be >= 1)
     * @return true if the order was placed successfully
     * @throws IllegalArgumentException if the item is unavailable or quantity is invalid
     */
    public boolean placeOrder(int itemId, int quantity) {
        // Validate quantity
        if (quantity < 1) {
            throw new IllegalArgumentException("Quantity must be at least 1.");
        }

        FoodItemDAO foodItemDAO = new FoodItemDAO();

        // Check item availability
        if (!foodItemDAO.isItemAvailable(itemId)) {
            throw new IllegalArgumentException(
                    "This food item is not available for ordering.");
        }

        // Fetch the current price from the database (do not trust UI price)
        BigDecimal price = foodItemDAO.getItemPrice(itemId);
        if (price == null) {
            throw new IllegalArgumentException("Food item not found in database.");
        }

        // Calculate total amount: price × quantity
        BigDecimal totalAmount = price.multiply(BigDecimal.valueOf(quantity));

        // Insert the order
        String sql = QueryGenerator.insertOrder();

        try (Connection conn = DatabaseConnection.getConnection();
             PreparedStatement pstmt = conn.prepareStatement(sql)) {

            pstmt.setInt(1, itemId);
            pstmt.setInt(2, quantity);
            pstmt.setBigDecimal(3, totalAmount);

            int rowsAffected = pstmt.executeUpdate();
            return rowsAffected > 0;

        } catch (SQLException e) {
            System.err.println("Error placing order: " + e.getMessage());
            return false;
        }
    }

    /**
     * Retrieves all orders with food item names using a JOIN.
     *
     * The JOIN is necessary because the orders table only stores item_id,
     * but we want to display the item_name for human readability.
     *
     * @return a list of String arrays:
     *         [order_id, item_name, quantity, total_amount, order_status]
     */
    public List<String[]> getAllOrders() {
        // This query uses JOIN - generated by QueryGenerator
        String sql = QueryGenerator.selectAllOrdersWithItemName();
        List<String[]> orders = new ArrayList<>();

        try (Connection conn = DatabaseConnection.getConnection();
             PreparedStatement pstmt = conn.prepareStatement(sql);
             ResultSet rs = pstmt.executeQuery()) {

            while (rs.next()) {
                String[] row = new String[5];
                row[0] = String.valueOf(rs.getInt("order_id"));
                row[1] = rs.getString("item_name");
                row[2] = String.valueOf(rs.getInt("quantity"));
                row[3] = rs.getBigDecimal("total_amount").toString();
                row[4] = rs.getString("order_status");
                orders.add(row);
            }

        } catch (SQLException e) {
            System.err.println("Error retrieving orders: " + e.getMessage());
        }

        return orders;
    }

    /**
     * Updates the status of an order.
     *
     * @param orderId   the order to update
     * @param newStatus the new status (must be Pending, Preparing, or Completed)
     * @return true if the update was successful
     * @throws IllegalArgumentException if the status is not valid
     */
    public boolean updateOrderStatus(int orderId, String newStatus) {
        // Validate status
        if (!VALID_STATUSES.contains(newStatus)) {
            throw new IllegalArgumentException(
                    "Invalid status: '" + newStatus + "'. " +
                    "Allowed: Pending, Preparing, Completed.");
        }

        String sql = QueryGenerator.updateOrderStatus();

        try (Connection conn = DatabaseConnection.getConnection();
             PreparedStatement pstmt = conn.prepareStatement(sql)) {

            pstmt.setString(1, newStatus);
            pstmt.setInt(2, orderId);

            int rowsAffected = pstmt.executeUpdate();
            return rowsAffected > 0;

        } catch (SQLException e) {
            System.err.println("Error updating order status: " + e.getMessage());
            return false;
        }
    }
}
